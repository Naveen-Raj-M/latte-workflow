"""
Read pre-computed ray paths from binary files generated by LATTE's forward solver.

This module provides an alternative to gradient-based ray tracing by directly reading
ray path coordinates from binary files. This is significantly faster when ray paths
have already been computed during the forward modeling stage.

Binary File Format (from latte_traveltime/src/module_raypath.f90):
    - Header: nrays (int32) - number of rays
    - Array: ray_npoints (int32 array, length=nrays) - points per ray
    - Data: For each ray, for each point: x, y, z coordinates (float32)

Note: Coordinates in binary files are in METERS, converted to KILOMETERS for output.
"""

import os
import gc
import struct
import numpy as np
import pandas as pd
from typing import Dict, Tuple, List, Optional, Set
from omegaconf import DictConfig
from tqdm import tqdm
from joblib import Parallel, delayed
import warnings

from postprocess.compute_ray_paths import (
    get_performance_setting,
    get_cache_path,
    is_cache_valid,
    initialize_cache,
    get_computed_shots,
    find_corrupted_shots,
    save_batch_to_cache,
    get_cache_stats,
    compute_config_hash
)


def read_raypath_binary_file(filepath: str, is_3d: bool = True) -> Tuple[int, np.ndarray, np.ndarray]:
    """
    Read a single raypath binary file.

    Binary format (Fortran stream I/O):
        [nrays: int32]
        [ray_npoints: int32 array of length nrays]
        [coordinates: float32, for each ray, for each point: x, (y), z]

    Args:
        filepath: Path to binary file
        is_3d: True for 3D (x,y,z), False for 2D (x,z)

    Returns:
        Tuple of:
            - nrays: number of rays
            - ray_npoints: array of points per ray (shape: nrays)
            - ray_coords: concatenated coordinates in METERS (shape: total_points, 2 or 3)

    Raises:
        FileNotFoundError: If file doesn't exist
        ValueError: If file format is invalid
    """
    if not os.path.exists(filepath):
        raise FileNotFoundError(f"Binary file not found: {filepath}")

    try:
        with open(filepath, 'rb') as f:
            # Read number of rays (int32, 4 bytes)
            nrays_bytes = f.read(4)
            if len(nrays_bytes) < 4:
                raise ValueError(f"File too short: {filepath}")

            nrays = struct.unpack('<i', nrays_bytes)[0]  # little-endian int32

            if nrays <= 0 or nrays > 1000000:  # Sanity check
                raise ValueError(f"Invalid nrays={nrays} in {filepath}")

            # Read ray_npoints array (nrays * int32)
            npoints_bytes = f.read(4 * nrays)
            if len(npoints_bytes) < 4 * nrays:
                raise ValueError(f"Incomplete ray_npoints array in {filepath}")

            ray_npoints = np.frombuffer(npoints_bytes, dtype=np.int32, count=nrays)

            # Validate ray_npoints
            if np.any(ray_npoints < 0) or np.any(ray_npoints > 1000000):
                raise ValueError(f"Invalid ray_npoints values in {filepath}")

            total_points = np.sum(ray_npoints)

            # Read coordinates (total_points * coords_per_point * float32)
            coords_per_point = 3 if is_3d else 2
            coords_bytes = f.read(4 * total_points * coords_per_point)

            if len(coords_bytes) < 4 * total_points * coords_per_point:
                raise ValueError(f"Incomplete coordinate data in {filepath}")

            # Parse coordinates as float32
            all_coords = np.frombuffer(coords_bytes, dtype=np.float32,
                                      count=total_points * coords_per_point)

            # Reshape to (total_points, coords_per_point)
            ray_coords = all_coords.reshape((total_points, coords_per_point))

            return nrays, ray_npoints, ray_coords

    except struct.error as e:
        raise ValueError(f"Binary format error in {filepath}: {e}")
    except Exception as e:
        raise ValueError(f"Error reading {filepath}: {e}")


def match_rays_to_receivers(ray_coords: np.ndarray, ray_npoints: np.ndarray,
                            receivers: List[Tuple[float, float, float]],
                            tolerance_km: float = 2.0) -> Tuple[np.ndarray, List[int]]:
    """
    Match rays to receivers by position (ray start point → receiver location).

    Since ray ordering in binary files may not match receiver ordering in CSV,
    we match each ray's starting point to the nearest receiver.

    Args:
        ray_coords: Ray coordinates in km (total_points, 3)
        ray_npoints: Points per ray (nrays,)
        receivers: Expected receiver positions in km
        tolerance_km: Maximum distance for matching (km)

    Returns:
        Tuple of:
            - reordered_ray_npoints: Ray point counts in receiver order
            - ray_indices: Mapping from receiver index to ray index (-1 if no match)
    """
    nrays = len(ray_npoints)

    # Extract starting point of each ray
    ray_starts = []
    offset = 0
    for i in range(nrays):
        n_pts = ray_npoints[i]
        if n_pts > 0:
            ray_starts.append(ray_coords[offset])
        else:
            ray_starts.append(np.array([np.nan, np.nan, np.nan]))
        offset += n_pts

    ray_starts = np.array(ray_starts)  # (nrays, 3)
    receivers_array = np.array(receivers)  # (n_receivers, 3)

    # For each receiver, find closest ray start point
    ray_indices = []
    used_rays = set()

    for i, receiver in enumerate(receivers_array):
        # Compute distances to all unused ray starts
        distances = np.linalg.norm(ray_starts - receiver, axis=1)

        # Mask out already used rays
        for used in used_rays:
            distances[used] = np.inf

        # Find closest ray
        closest_ray = np.argmin(distances)
        min_dist = distances[closest_ray]

        if min_dist < tolerance_km:
            ray_indices.append(closest_ray)
            used_rays.add(closest_ray)
        else:
            # No matching ray found for this receiver
            ray_indices.append(-1)
            if min_dist < 10.0:  # Only warn if somewhat close
                warnings.warn(
                    f"Receiver {i}: No matching ray found (closest: {min_dist:.3f} km)"
                )

    return ray_indices


def validate_ray_receiver_match(matched_ray_indices: List[int],
                                 ray_coords: np.ndarray,
                                 ray_npoints: np.ndarray,
                                 receivers: List[Tuple[float, float, float]],
                                 source_pos: Tuple[float, float, float]) -> bool:
    """
    Validate that matched rays reach the source.

    Args:
        matched_ray_indices: Mapping from receiver index to ray index
        ray_coords: Ray coordinates in km (total_points, 3)
        ray_npoints: Points per ray
        receivers: Receiver positions in km
        source_pos: Source position in km

    Returns:
        True if validation passes
    """
    n_matched = sum(1 for idx in matched_ray_indices if idx >= 0)
    n_receivers = len(receivers)

    if n_matched < n_receivers * 0.8:  # Warn if <80% matched
        warnings.warn(
            f"Only {n_matched}/{n_receivers} receivers matched to rays ({n_matched/n_receivers*100:.1f}%)"
        )
        return False

    # Check a few rays reach the source
    source = np.array(source_pos)
    check_count = min(5, n_matched)

    # Get indices of matched rays to check
    valid_indices = [i for i, ray_idx in enumerate(matched_ray_indices) if ray_idx >= 0]
    check_indices = valid_indices[:check_count] if len(valid_indices) >= check_count else valid_indices

    offset = 0
    for ray_idx in range(len(ray_npoints)):
        n_pts = ray_npoints[ray_idx]

        # Check if this ray is in our check list
        if ray_idx in [matched_ray_indices[i] for i in check_indices]:
            ray_end = ray_coords[offset + n_pts - 1]
            dist_to_source = np.linalg.norm(ray_end - source)

            if dist_to_source > 10.0:  # 10 km tolerance for source
                warnings.warn(
                    f"Ray {ray_idx} may not reach source: {dist_to_source:.3f} km away"
                )

        offset += n_pts

    return True


def process_single_shot_from_binary(
    shot_id: int,
    phase: str,
    binary_dir: str,
    df_gt: pd.DataFrame,
    weight_column: Optional[str] = None,
    verbose: bool = False,
    validate_match: bool = True
) -> Optional[Dict]:
    """
    Process a single shot by reading its binary raypath file.

    Args:
        shot_id: Shot ID
        phase: Wave phase ('p' or 's')
        binary_dir: Directory containing binary raypath files
        df_gt: Ground truth dataframe with source-receiver pairs
        weight_column: Column name for weights (None = use 1.0)
        verbose: Print warnings
        validate_match: Validate ray-receiver matching

    Returns:
        Dictionary with:
            - 'source': source position (x, y, z) in km
            - 'receivers': list of receiver positions in km
            - 'weights': list of weights
            - 'ray_paths': list of ray path arrays
        Returns None if shot cannot be processed
    """
    try:
        # Construct binary file path
        binary_file = f"{binary_dir}/shot_{shot_id}_raypath_{phase}.bin"

        if not os.path.exists(binary_file):
            if verbose:
                warnings.warn(f"Binary file not found: {binary_file}")
            return None

        # Get shot data from ground truth
        shot_data = df_gt[df_gt['shot_id'] == shot_id]

        if len(shot_data) == 0:
            if verbose:
                warnings.warn(f"No ground truth data for shot {shot_id}")
            return None

        # Get source position (in km)
        source_row = shot_data.iloc[0]
        source_pos = (
            source_row['event_x_transformed'],
            source_row['event_y_transformed'],
            source_row['event_z_transformed']
        )

        # Get receivers and weights
        receivers = []
        weights = []
        for _, row in shot_data.iterrows():
            receiver_pos = (
                row['station_x_transformed'],
                row['station_y_transformed'],
                row['station_z_transformed']
            )
            receivers.append(receiver_pos)

            if weight_column and weight_column in row:
                weights.append(row[weight_column])
            else:
                weights.append(1.0)

        # Detect 2D vs 3D based on source position
        # If all y-coordinates are the same, assume 2D
        is_3d = True
        if len(shot_data) > 1:
            y_coords = shot_data['station_y_transformed'].values
            if np.allclose(y_coords, y_coords[0], atol=1e-6):
                is_3d = False

        # Read binary file
        _, ray_npoints, ray_coords_m = read_raypath_binary_file(binary_file, is_3d=is_3d)

        # Convert coordinates from meters to kilometers
        ray_coords_km = ray_coords_m / 1000.0

        # Match rays to receivers by position (ray start → receiver location)
        matched_ray_indices = match_rays_to_receivers(
            ray_coords_km, ray_npoints, receivers, tolerance_km=2.0
        )

        # Validate ray-receiver matching
        if validate_match:
            valid = validate_ray_receiver_match(
                matched_ray_indices, ray_coords_km, ray_npoints, receivers, source_pos
            )
            if not valid and verbose:
                warnings.warn(f"Shot {shot_id}: Ray-receiver validation failed")

        # Build ray paths in receiver order (not binary file order)
        ray_paths = []
        reordered_receivers = []
        reordered_weights = []

        # Pre-compute offsets for each ray in binary file
        ray_offsets = np.zeros(len(ray_npoints) + 1, dtype=int)
        ray_offsets[1:] = np.cumsum(ray_npoints)

        for i, ray_idx in enumerate(matched_ray_indices):
            if ray_idx >= 0 and ray_idx < len(ray_npoints):
                # Found a matching ray
                n_pts = ray_npoints[ray_idx]
                offset = ray_offsets[ray_idx]

                if n_pts > 0:
                    ray_path = ray_coords_km[offset:offset + n_pts]
                    ray_paths.append(ray_path)
                else:
                    # Empty ray - use dummy single point at receiver
                    ray_paths.append(np.array([receivers[i]]))

                reordered_receivers.append(receivers[i])
                reordered_weights.append(weights[i])
            else:
                # No matching ray for this receiver - create dummy ray
                if verbose:
                    warnings.warn(f"Shot {shot_id}: No ray found for receiver {i}, creating dummy")
                ray_paths.append(np.array([receivers[i]]))
                reordered_receivers.append(receivers[i])
                reordered_weights.append(weights[i])

        # Update receivers and weights to match reordered data
        receivers = reordered_receivers
        weights = reordered_weights

        return {
            'source': source_pos,
            'receivers': receivers,
            'weights': weights,
            'ray_paths': ray_paths
        }

    except Exception as e:
        if verbose:
            warnings.warn(f"Error processing shot {shot_id}: {e}")
        return None


def compute_all_ray_paths_from_binary(
    config: DictConfig,
    subsample_during_computation: bool = False,
    filter_shot_ids: Optional[Set[int]] = None
) -> Dict[str, Dict]:
    """
    Read all ray paths from binary files and save to HDF5 cache.

    This function reads pre-computed ray paths from binary files generated by
    LATTE's forward solver, converts them to the standard HDF5 cache format,
    and processes them in batches to manage memory usage.

    Args:
        config: Ray path diagnosis configuration
        subsample_during_computation: If True, apply subsampling before processing
        filter_shot_ids: Optional set of shot IDs to process

    Returns:
        Dictionary with phase keys ('p', 's') containing ray path data.
        If load_cache_for_downstream=False, returns empty result.
    """
    print("\n" + "="*80)
    print("READING RAY PATHS FROM BINARY FILES")
    print("="*80)

    # Get binary directory
    binary_dir = getattr(config, 'raypath_binary_dir', None)
    if not binary_dir:
        raise ValueError("raypath_binary_dir must be specified when raypath_source='binary'")

    if not os.path.exists(binary_dir):
        raise FileNotFoundError(f"Binary raypath directory not found: {binary_dir}")

    print(f"\nBinary raypath directory: {binary_dir}")

    # Get cache settings
    force_recompute = getattr(config, 'force_recompute', False)
    cache_path = get_cache_path(config)

    print(f"\nCache settings:")
    print(f"  Cache file: {cache_path}")
    print(f"  Force recompute: {force_recompute}")

    # Check cache validity
    if not force_recompute and is_cache_valid(cache_path, config):
        print(f"  Cache is VALID (config hash matches)")
        cache_stats = get_cache_stats(cache_path)
        print(f"  Existing cache: {cache_stats['p_wave_rays']} P-wave rays, "
              f"{cache_stats['s_wave_rays']} S-wave rays ({cache_stats['file_size_mb']:.1f} MB)")
    else:
        if force_recompute:
            print(f"  Force recompute requested - will create new cache")
        else:
            print(f"  Cache invalid or doesn't exist - will create new cache")

        # Initialize new cache
        initialize_cache(cache_path, config)

    # Load ground truth data
    print(f"\nLoading ground truth data: {config.ground_truth_csv}")
    df_gt = pd.read_csv(config.ground_truth_csv)

    # Convert coordinates from meters to kilometers if needed
    # (Binary files are in meters, ground truth should match)
    coordinate_columns = [
        'event_x_transformed', 'event_y_transformed', 'event_z_transformed',
        'station_x_transformed', 'station_y_transformed', 'station_z_transformed'
    ]

    # Check if coordinates are in meters (values > 1000 suggest meters)
    sample_col = 'event_x_transformed'
    if sample_col in df_gt.columns and df_gt[sample_col].abs().max() > 1000:
        print("  Converting coordinates from meters to kilometers")
        for col in coordinate_columns:
            if col in df_gt.columns:
                df_gt[col] = df_gt[col] / 1000.0
    else:
        print("  Coordinates already in kilometers")

    print(f"  Total source-receiver pairs: {len(df_gt)}")

    # Determine phase types to process
    phase_type = getattr(config, 'phase_type', 'both')
    phase_types = []
    if phase_type in ['both', 'p']:
        phase_types.append('p')
    if phase_type in ['both', 's']:
        phase_types.append('s')

    result = {}

    # Get performance settings
    parallel_processing = get_performance_setting(config, 'parallel_processing', True)
    n_jobs = get_performance_setting(config, 'n_jobs', 1) if parallel_processing else 1
    backend = get_performance_setting(config, 'backend', 'loky')
    batch_size = get_performance_setting(config, 'batch_size', 'auto')

    # Get weight column (for DWS)
    weight_column = None
    if hasattr(config, 'dws') and hasattr(config.dws, 'weight_column'):
        weight_column = config.dws.weight_column

    max_shots = getattr(config, 'max_shots', 0)

    print(f"\nGlobal settings:")
    print(f"  Parallel processing: {parallel_processing} (n_jobs={n_jobs}, backend={backend})")
    print(f"  Source: Binary raypath files")

    for phase in phase_types:
        print(f"\n{'='*80}")
        print(f"Processing {phase.upper()}-wave ray paths from binary")
        print(f"{'='*80}")

        # Get already computed shots from cache
        computed_shots = get_computed_shots(cache_path, phase) if not force_recompute else set()
        if computed_shots:
            print(f"  Found {len(computed_shots)} shots already in cache")

        # Check for corrupted shots if requested
        corrupted_shots = set()
        fix_corrupted = getattr(config, 'fix_corrupted_shots', False)
        if fix_corrupted and not force_recompute and computed_shots:
            print(f"  Scanning for corrupted shots...")
            corrupted_shots = set(find_corrupted_shots(cache_path, phase))
            if corrupted_shots:
                print(f"  Found {len(corrupted_shots)} corrupted shots: {sorted(list(corrupted_shots))}")
                print(f"  These will be recomputed")
            else:
                print(f"  No corrupted shots found")

        # Filter by phase if column exists
        if 'phase' in df_gt.columns:
            df_phase = df_gt[df_gt['phase'].str.upper() == phase.upper()].copy()
        else:
            df_phase = df_gt.copy()

        # Get unique shots
        unique_shots = df_phase['shot_id'].unique()

        # Apply event filtering if provided
        if filter_shot_ids is not None and subsample_during_computation:
            n_shots_before = len(unique_shots)
            unique_shots = np.array([s for s in unique_shots if s in filter_shot_ids])
            print(f"  EVENT FILTER: Selected {len(unique_shots)}/{n_shots_before} shots from event ID list")

        # Limit number of shots if specified
        if max_shots > 0:
            unique_shots = unique_shots[:max_shots]
            print(f"  Limited to {max_shots} shots")

        # Filter out already computed shots (but include corrupted ones)
        shots_to_compute = [s for s in unique_shots if (s not in computed_shots) or (s in corrupted_shots)]

        if len(shots_to_compute) < len(unique_shots):
            n_skipped = len(unique_shots) - len(shots_to_compute)
            n_corrupted = len([s for s in shots_to_compute if s in corrupted_shots])
            print(f"  Skipping {n_skipped} already computed shots")
            if n_corrupted > 0:
                print(f"  Will recompute {n_corrupted} corrupted shots")
            print(f"  Will process {len(shots_to_compute)} total shots ({len(shots_to_compute) - n_corrupted} new + {n_corrupted} recomputed)")

        # Get weight column if it exists
        has_weights = weight_column is not None and weight_column in df_phase.columns
        if has_weights:
            print(f"  Using weight column: '{weight_column}'")
        else:
            print(f"  No weights found, using uniform weights (1.0)")

        # Apply subsampling if requested
        if subsample_during_computation and shots_to_compute:
            subsample_fraction = getattr(config, 'subsample_fraction', 1.0)
            if subsample_fraction < 1.0:
                n_shots_original = len(shots_to_compute)
                n_shots_to_compute = max(1, int(n_shots_original * subsample_fraction))

                # Random subsample of shots
                shots_to_compute = list(np.random.choice(
                    shots_to_compute,
                    n_shots_to_compute,
                    replace=False
                ))

                print(f"  SUBSAMPLE: Selected {len(shots_to_compute)}/{n_shots_original} shots ({subsample_fraction*100:.1f}%)")

        # Process in batches
        if shots_to_compute:
            # Calculate batch size
            if batch_size == 'auto' or batch_size is None:
                shots_per_batch = 500  # Binary reading is fast, larger batches OK
            else:
                shots_per_batch = int(batch_size)

            # Sort shot IDs for better disk locality
            shots_to_compute = sorted(shots_to_compute)
            n_shots = len(shots_to_compute)
            n_batches = (n_shots + shots_per_batch - 1) // shots_per_batch

            print(f"\n  Processing {n_shots} shots in {n_batches} batches ({shots_per_batch} shots/batch)")
            print(f"  Each batch will be saved to cache and memory cleared")

            total_rays_computed = 0
            total_failed = 0

            for batch_idx in range(n_batches):
                batch_start = batch_idx * shots_per_batch
                batch_end = min(batch_start + shots_per_batch, n_shots)
                batch_shot_ids = shots_to_compute[batch_start:batch_end]

                print(f"\n  Batch {batch_idx + 1}/{n_batches}: Processing {len(batch_shot_ids)} shots...")

                # Process batch in parallel
                batch_results_raw = Parallel(
                    n_jobs=n_jobs,
                    backend=backend,
                    verbose=0
                )(
                    delayed(process_single_shot_from_binary)(
                        shot_id,
                        phase,
                        binary_dir,
                        df_phase,
                        weight_column,
                        verbose=False,  # Suppress per-shot warnings
                        validate_match=True
                    )
                    for shot_id in tqdm(batch_shot_ids, desc=f"Batch {batch_idx + 1}/{n_batches}")
                )

                # Format results for cache storage
                batch_results_for_cache = {}
                batch_rays = 0
                batch_failed = 0

                for shot_idx, shot_id in enumerate(batch_shot_ids):
                    shot_result = batch_results_raw[shot_idx]

                    if shot_result is None:
                        batch_failed += len(df_phase[df_phase['shot_id'] == shot_id])
                        continue

                    batch_results_for_cache[shot_id] = shot_result
                    batch_rays += len(shot_result['ray_paths'])

                # Clear raw results
                del batch_results_raw
                gc.collect()

                # Save batch to cache
                if batch_results_for_cache:
                    saved = save_batch_to_cache(cache_path, phase, batch_results_for_cache)
                    print(f"    Saved {saved} rays to cache")

                total_rays_computed += batch_rays
                total_failed += batch_failed

                # Clear batch results
                del batch_results_for_cache
                gc.collect()

                print(f"    Batch complete: {batch_rays} rays read, {batch_failed} failed")
                print(f"    Total so far: {total_rays_computed} rays")

            print(f"\n  Processing complete: {total_rays_computed} rays read from binary, {total_failed} failed")

        # Load results from cache if needed for downstream use
        load_for_downstream = getattr(config, 'load_cache_for_downstream', False)

        if load_for_downstream:
            from postprocess.compute_ray_paths import load_rays_from_cache

            print(f"\n  Loading all {phase.upper()}-wave rays from cache for downstream use...")
            phase_result = load_rays_from_cache(cache_path, phase)
            print(f"    Loaded {len(phase_result['ray_paths'])} rays")

            # Handle event filtering for visualization
            if filter_shot_ids is not None and not subsample_during_computation:
                viz_indices = [i for i, sid in enumerate(phase_result['shot_ids']) if sid in filter_shot_ids]
                print(f"  EVENT FILTER: Will use {len(viz_indices)}/{len(phase_result['ray_paths'])} rays")

                phase_result['viz_ray_paths'] = [phase_result['ray_paths'][i] for i in viz_indices]
                phase_result['viz_sources'] = [phase_result['sources'][i] for i in viz_indices]
                phase_result['viz_receivers'] = [phase_result['receivers'][i] for i in viz_indices]
                phase_result['viz_shot_ids'] = [phase_result['shot_ids'][i] for i in viz_indices]

            result[phase] = phase_result
        else:
            print(f"\n  Skipping cache load (load_cache_for_downstream=false)")
            print(f"  Ray paths are saved in cache: {cache_path}")
            # Return empty result for this phase
            result[phase] = {
                'ray_paths': [],
                'sources': [],
                'receivers': [],
                'shot_ids': [],
                'weights': []
            }

    # Print cache stats
    print(f"\n" + "="*80)
    print("CACHE SUMMARY")
    print("="*80)
    cache_stats = get_cache_stats(cache_path)
    print(f"  Cache file: {cache_path}")
    print(f"  File size: {cache_stats['file_size_mb']:.2f} MB")
    print(f"  P-wave: {cache_stats['p_wave_shots']} shots, {cache_stats['p_wave_rays']} rays")
    print(f"  S-wave: {cache_stats['s_wave_shots']} shots, {cache_stats['s_wave_rays']} rays")

    print("\n" + "="*80)
    print("BINARY RAY PATH READING COMPLETE")
    print("="*80)

    return result
